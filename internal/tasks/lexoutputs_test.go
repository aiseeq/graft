func TestLexCodexFromHeader(t *testing.T) {
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	codex := filepath.ToSlash(filepath.Join(t.TempDir(), "codex-one.v2"))
	frontMatterCodex := filepath.ToSlash(filepath.Join(t.TempDir(), "codex-with-front-matter"))
	for _, tt := range []struct {
		name, text, want string
		found, wantErr   bool
	}{
		{name: "body header", text: fmt.Sprintf("<!-- lex: built from %s/manifest/projectA%%2DCLAUDE.md.yaml. -->\n", codex), want: codex, found: true},
		{name: "front matter", text: fmt.Sprintf("---\ntitle: Notes\n---\n<!-- lex: %s/manifest/projectA-CLAUDE.md.yaml -->\n", frontMatterCodex), want: frontMatterCodex, found: true},
		{name: "second body line", text: fmt.Sprintf("title\n<!-- lex: %s/manifest/projectA-CLAUDE.md.yaml -->\n", codex)},
		{name: "missing manifest", text: "<!-- lex: generated by lex -->\n", found: true, wantErr: true},
		{name: "home codex", text: "<!-- lex: built from ~/.claude/codex/manifest/projectA-CLAUDE.md.yaml. -->\n", want: filepath.Join(home, ".claude", "codex"), found: true},
		{name: "a tilde not of the home", text: "<!-- lex: built from ~other/codex/manifest/projectA-CLAUDE.md.yaml. -->\n", want: "~other/codex", found: true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			lines := strings.Split(strings.TrimSuffix(tt.text, "\n"), "\n")
			i := 0
			codex, found, err := lexCodexFromHeader(func() (string, error) {
				if i == len(lines) {
					return "", io.EOF
				}
				line := lines[i]
				i++
				return line, nil
			})
			if (err != nil) != tt.wantErr {
				t.Fatalf("error = %v, wantErr %t", err, tt.wantErr)
			}
			if codex != tt.want || found != tt.found {
				t.Fatalf("got (%q, %t), want (%q, %t)", codex, found, tt.want, tt.found)
			}
		})
	}
}

func TestLexCheckArgs(t *testing.T) {
	main := t.TempDir()
	tree := t.TempDir()
	base := []string{"check", "--codex", "codex", "--outputs-under", filepath.Clean(main)}
	got, err := lexCheckArgs("codex", main, main)
	if err != nil || strings.Join(got, "\x00") != strings.Join(base, "\x00") {
		t.Fatalf("same root args = %q, %v; want %q", got, err, base)
	}
	wantDifferent := append(append([]string{}, base...), "--tree", filepath.Clean(tree))
	got, err = lexCheckArgs("codex", main, tree)
	if err != nil || strings.Join(got, "\x00") != strings.Join(wantDifferent, "\x00") {
		t.Fatalf("different root args = %q, %v; want %q", got, err, wantDifferent)
	}
	if runtime.GOOS == "windows" {
		t.Skip("creates a directory symlink")
	}
	alias := filepath.Join(t.TempDir(), "same-root")
	if err := os.Symlink(main, alias); err != nil {
		t.Fatal(err)
	}
	got, err = lexCheckArgs("codex", main, alias)
	if err != nil || strings.Join(got, "\x00") != strings.Join(base, "\x00") {
		t.Fatalf("symlink alias args = %q, %v; want %q", got, err, base)
	}
}

func TestLexMainCheckout(t *testing.T) {
	main := t.TempDir()
	if out, err := exec.Command("git", "init", "-q", main).CombinedOutput(); err != nil {
		t.Fatalf("git init: %v\n%s", err, out)
	}
	repo, err := gitx.Open(main)
	if err != nil {
		t.Fatal(err)
	}
	got, err := lexMainCheckout(repo)
	if err != nil || filepath.Clean(got) != filepath.Clean(main) {
		t.Fatalf("main checkout = %q, %v; want %q", got, err, main)
	}
	common := filepath.Join(main, ".git")
	if _, err := lexMainCheckout(&gitx.Repo{Root: common, GitDir: common, CommonDir: common}); err == nil || !strings.Contains(err.Error(), "bare repository") {
		t.Fatalf("bare repository error = %v", err)
	}
}

type lexReadError struct{}

func (lexReadError) Read([]byte) (int, error) { return 0, errors.New("synthetic read failure") }

func TestReadLexHeaderBoundedStart(t *testing.T) {
	codex := filepath.ToSlash(filepath.Join(t.TempDir(), "codex-bounded"))
	header := fmt.Sprintf("<!-- lex: %s/manifest/projectA-CLAUDE.md.yaml -->", codex)
	for _, tt := range []struct {
		name, content, want string
		wantReadErr         bool
	}{
		{name: "long first line", content: header + strings.Repeat("x", lexHeaderReadLimit)},
		{name: "unclosed front matter", content: "---\ntitle: notes\n" + strings.Repeat("x", 100)},
		{name: "header within bound", content: "---\ntitle: notes\n---\n" + header, want: codex},
		{name: "real read error", wantReadErr: true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			var reader io.Reader = strings.NewReader(tt.content)
			if tt.wantReadErr {
				reader = lexReadError{}
			}
			got, found, err := readLexHeader(reader)
			if tt.wantReadErr {
				if _, _, err := lexHeaderForFile("notes.md", reader); err == nil || !strings.Contains(err.Error(), "notes.md") || !strings.Contains(err.Error(), "synthetic read failure") {
					t.Fatalf("read error = %v", err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if got != tt.want || found != (tt.want != "") {
				t.Fatalf("got (%q, %t), want (%q, %t)", got, found, tt.want, tt.want != "")
			}
		})
	}
}
